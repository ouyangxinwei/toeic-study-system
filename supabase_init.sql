-- TOEIC错题学习系统：Supabase 初始化 SQL
-- 在 Supabase Dashboard -> SQL Editor 中整段执行。
-- 当前前端无登录功能，因此下面的 anon 写入策略意味着任何拿到项目公开 key 的人都能修改题库。
-- 若部署给多人使用，建议接入 Supabase Auth 并改为 authenticated 策略。

create table if not exists public.toeic_questions (
  id bigint generated by default as identity primary key,
  set_id integer not null check (set_id between 1 and 15),
  part_id integer not null check (part_id between 1 and 7),
  question_id text not null,
  title text not null default '',
  options jsonb not null default '{}'::jsonb,
  correct_answer text not null default '',
  audio jsonb not null default '{"type":"none"}'::jsonb,
  note text not null default '',
  status text not null default 'unanswered' check (status in ('unanswered','wrong','correct','mastered')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (set_id, question_id)
);

create index if not exists idx_toeic_questions_set_part on public.toeic_questions (set_id, part_id);
alter table public.toeic_questions enable row level security;
grant select, insert, update on public.toeic_questions to anon, authenticated;
grant usage, select on sequence public.toeic_questions_id_seq to anon, authenticated;

-- 当前版本没有登录系统，采用公开读写以便录入/同步功能工作。
drop policy if exists "TOEIC public read questions" on public.toeic_questions;
drop policy if exists "TOEIC public insert questions" on public.toeic_questions;
drop policy if exists "TOEIC public update questions" on public.toeic_questions;
create policy "TOEIC public read questions" on public.toeic_questions for select to anon, authenticated using (true);
create policy "TOEIC public insert questions" on public.toeic_questions for insert to anon, authenticated with check (true);
create policy "TOEIC public update questions" on public.toeic_questions for update to anon, authenticated using (true) with check (true);

